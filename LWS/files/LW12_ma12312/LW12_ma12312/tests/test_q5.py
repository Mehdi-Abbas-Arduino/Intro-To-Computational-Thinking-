@pytest.mark.parametrize("input_lines, expected, visible", q5_testcases)
def test_q5(monkeypatch, input_lines, expected, visible):
    input_iterator = iter(input_lines)
    monkeypatch.setattr('builtins.input', lambda prompt="": next(input_iterator))
    result = contacts()
    assert isinstance(result, dict), "The function must return a dictionary."
    for phone_numbers in result.values():
        assert isinstance(phone_numbers, list), "Each contact must map to a list."
        assert phone_numbers == sorted(set(phone_numbers)), "Phone numbers must be unique and sorted."
    if visible:
        assert result == expected
    else:
        assert hashcode(result) == expected

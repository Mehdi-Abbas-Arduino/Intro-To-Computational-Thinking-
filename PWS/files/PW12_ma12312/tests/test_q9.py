@pytest.mark.parametrize("comment,expected,is_visible", q9_testcases)
def test_q9(comment, expected, is_visible):
    original = copy.deepcopy(comment)
    working_comment = copy.deepcopy(comment)
    result = count_reported_comments(working_comment)
    assert type(result) is int
    assert working_comment == original
    if is_visible:
        assert result == expected
    else:
        assert hashcode(result) == expected

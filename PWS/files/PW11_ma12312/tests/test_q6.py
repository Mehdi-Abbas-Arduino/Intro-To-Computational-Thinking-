def test_q6_rules():
    validate_rules(q6, 6)


def test_q6_recursion_executed():
    assert_recursion_executed(q6, q6.minmax, ([0, -3, 6, 4, 9, 1],))


@pytest.mark.parametrize('temperatures, expected, visible', q6_testcases)
def test_q6(temperatures, expected, visible):
    input_list = temperatures[:]
    outcome = run_solution(6, 'minmax', input_list)
    result = outcome.value
    assert outcome.arguments_after[0] == temperatures, "Do not modify temperatures."
    assert outcome.result_type == 'list' and len(result) == 2, (
        "Return a list [smallest, largest].")
    if visible:
        assert result == expected
    else:
        assert hashlib.sha256(str(result).encode("utf-8")).hexdigest() == expected

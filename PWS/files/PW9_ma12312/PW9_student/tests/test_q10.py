@pytest.mark.parametrize(
    "board, diceRolls, expected, visible",
    CASES,
    ids=[f"{'visible' if c[3] else 'hidden'}-{i:02d}" for i, c in enumerate(CASES, 1)],
)
def test_q10(board, diceRolls, expected, visible):
    original_board = deepcopy(board)
    original_rolls = diceRolls[:]
    result = q10.playSandL(board, diceRolls)

    assert isinstance(result, list), "playSandL() must return a list."
    assert len(result) == len(diceRolls), "Return exactly one position per dice roll."
    assert all(
        type(pos) is list and len(pos) == 2 and all(type(index) is int for index in pos)
        for pos in result
    ), "Each returned position must be a list [row, column] of integers."

    if visible:
        assert result == expected, f"Expected {expected}, got {result}."
    else:
        digest = hashlib.sha256(str(result).encode("utf-8")).hexdigest()
        assert digest == expected, "Incorrect positions for this hidden test case."

    assert board == original_board, "playSandL() must not modify the original board."
    assert diceRolls == original_rolls, "playSandL() must not modify diceRolls."
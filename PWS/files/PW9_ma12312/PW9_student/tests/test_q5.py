@pytest.mark.parametrize("n, start, stop, expected, visible", q5_testcases)
def test_collatz_cousin(capsys, n, start, stop, expected, visible):
    collatz_cousin(n, start, stop)
    captured = capsys.readouterr()
    assert not captured.err, "The function should not print errors to stderr."

    lines = [line.rstrip() for line in captured.out.splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    actual = "\n".join(lines)

    if visible:
        assert actual == expected, (
            f"Incorrect printed sequences for family {n}, range {start} to {stop}."
        )
    else:
        assert hashcode(actual) == expected, (
            f"Incorrect printed sequences for hidden family {n}, range {start} to {stop}."
        )
@pytest.mark.parametrize("all_charges, tab_id, expected, visible", q2_testcases)
def test_q2(all_charges, tab_id, expected, visible):
    original_charges = deepcopy(all_charges)
    actual = my_bill(all_charges, tab_id)

    assert all_charges == original_charges, (
        "The original all_charges nested list must not be modified."
    )
    assert isinstance(actual, list), "my_bill must return a list."

    if visible:
        assert actual == expected, f"{actual!r} != {expected!r}"
    else:
        assert hashcode(actual) == expected, (
            "Incorrect visit totals for this hidden test case."
        )

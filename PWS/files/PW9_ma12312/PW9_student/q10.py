def playSandL(board, diceRolls):
    n = len(board)
    row = n - 1
    col = 0
    lst = []

    for roll in diceRolls:
        for i in range(roll):
            if (n - 1 - row) % 2 == 0:
                if col < n - 1:
                    col += 1
                else:
                    row -= 1
            else:
                if col > 0:
                    col -= 1
                else:
                    row -= 1

        if isinstance(board[row][col], list):
            destination = board[row][col]
            row = destination[0]
            col = destination[1]

        lst.append([row, col])

    return lst




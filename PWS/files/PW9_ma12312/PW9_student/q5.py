def collatz_cousin(n, start, stop):
    if n == -2:
        cycles = [0, 3, 15, 51]
    elif n == -1:
        cycles = [1, 5, 17]
    elif n == 0:
        cycles = [1]
    elif n == 1:
        cycles = [3]
    else:
        cycles = [1, 5, 19, 23, 187]

    for i in range(start, stop + 1):
        x = i
        lst = [x]

        while True:
            if x % 2 == 0:
                x = x // 2
            else:
                x = 3 * x + 2 * n + 1

            lst.append(x)

            if x in cycles:
                break

        new_lst = []

        for num in lst: 
            new_lst.append(str(num))

        result = ", ".join(new_lst)

        print(result)



